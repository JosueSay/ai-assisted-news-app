"""Exporta tipos y catálogo para Expo; no abre DB, configuración ni secretos."""

import argparse
import json
from pathlib import Path

from .models import (
    ConfidenceLevel,
    ImageType,
    LocationLevel,
    NewsStatus,
    ResponseIntent,
    ResponseStrategy,
    SourceType,
    UserRole,
    VerificationStatus,
)
from .presentation import topic_catalog

DEFAULT_OUTPUT = (
    Path(__file__).resolve().parents[2] / "frontend/src/generated/newsContract.ts"
)


def render_contract() -> str:
    catalog = json.dumps(topic_catalog(), ensure_ascii=False, indent=2)
    lines = [
        "// Generated by python -m news.export_contract. Do not edit by hand.",
        f"export const CATEGORIES = {catalog} as const;",
        'export type CategoryId = (typeof CATEGORIES)[number]["id"];',
    ]
    for enum in (
        ImageType,
        LocationLevel,
        SourceType,
        VerificationStatus,
        NewsStatus,
        UserRole,
        ResponseStrategy,
        ResponseIntent,
        ConfidenceLevel,
    ):
        values = " | ".join(json.dumps(item.value) for item in enum)
        lines.append(f"export type {enum.__name__} = {values};")
    return "\n\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render_contract()
    if args.check:
        if (
            not args.output.is_file()
            or args.output.read_text(encoding="utf-8") != expected
        ):
            parser.exit(
                1, "Frontend contract is out of date. Run make news-contract.\n"
            )
        print("Frontend news contract: OK")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected, encoding="utf-8")
        print("Frontend news contract generated.")


if __name__ == "__main__":
    main()
